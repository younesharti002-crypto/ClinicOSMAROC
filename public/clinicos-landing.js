function switchLang(lang, sourceButton) {
  const dictionary = translations[lang] || translations.ar;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) element.placeholder = dictionary[key];
  });

  document.querySelectorAll("img[data-alt-ar]").forEach((image) => {
    image.alt = lang === "fr" ? image.dataset.altFr : image.dataset.altAr;
  });

  const whatsappUrl = `https://wa.me/212644344034?text=${encodeURIComponent(dictionary.whatsapp_message)}`;
  document.querySelectorAll("[data-whatsapp]").forEach((link) => {
    link.href = whatsappUrl;
  });

  document.querySelectorAll(".lang-btn").forEach((button) => button.classList.remove("active"));
  if (sourceButton) sourceButton.classList.add("active");

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = dictionary.page_title;
  document.body.style.fontFamily = lang === "ar"
    ? "'Cairo','Poppins',sans-serif"
    : "'Poppins','Cairo',sans-serif";

  localStorage.setItem("preferredLang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("preferredLang") || "ar";
  const button = savedLang === "fr"
    ? document.querySelector(".lang-btn:nth-child(2)")
    : document.querySelector(".lang-btn:nth-child(1)");
  switchLang(savedLang, button);

  const trackedUtmKeys = ["utm_source", "utm_medium", "utm_campaign", "utm_content", "utm_term"];
  const query = new URLSearchParams(window.location.search);
  trackedUtmKeys.forEach((key) => {
    const incomingValue = query.get(key);
    if (incomingValue) sessionStorage.setItem(key, incomingValue);
    const field = document.querySelector(`#kit-lead-form input[name="${key}"]`);
    if (field) field.value = sessionStorage.getItem(key) || "";
  });

  const trackEvent = (eventName) => {
    window.dataLayer = window.dataLayer || [];
    window.dataLayer.push({ event: eventName, page_language: document.documentElement.lang });
  };

  document.querySelectorAll("[data-track-event]").forEach((element) => {
    element.addEventListener("click", () => trackEvent(element.dataset.trackEvent));
  });

  const leadForm = document.querySelector("#kit-lead-form");
  if (leadForm) {
    let formStarted = false;
    leadForm.addEventListener("focusin", () => {
      if (formStarted) return;
      formStarted = true;
      trackEvent("diagnostic_form_start");
    });
    leadForm.addEventListener("submit", () => trackEvent("diagnostic_form_submit"));
  }
});

document.querySelectorAll(".faq-question").forEach((question) => {
  question.addEventListener("click", () => {
    const item = question.parentElement;
    const isActive = item.classList.contains("active");
    document.querySelectorAll(".faq-item").forEach((faq) => faq.classList.remove("active"));
    if (!isActive) item.classList.add("active");
  });
});

document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
  anchor.addEventListener("click", function (event) {
    const target = document.querySelector(this.getAttribute("href"));
    if (!target) return;
    event.preventDefault();
    target.scrollIntoView({ behavior: "smooth", block: "start" });
  });
});

